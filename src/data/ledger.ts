import type { Observation, Totals } from '@/types/observatory'

function row(
  id: string,
  obsDate: string,
  target: string,
  status: Observation['status'],
  reason: Observation['reason'],
  frames: number,
  note: string,
  fit?: { oc: number; ocErr: number; depth: number; depthErr: number; scatter: number },
): Observation {
  return {
    id,
    target,
    obsDate,
    dataset: `MObs_${target.replace(/[^A-Za-z0-9]/g, '')}_${obsDate.replace(/-/g, '')}`,
    status,
    reason,
    ocMin: fit ? { value: fit.oc, err: fit.ocErr } : null,
    depth: fit ? { value: fit.depth, err: fit.depthErr } : null,
    scatterPct: fit ? fit.scatter : null,
    note,
    image: fit ? `/images/${id}-lightcurve.png` : null,
    manifest: 'manifest.json',
    frames,
    obscode: null,
  }
}

